# Project: FieldNotes
def next_action_suggestion(state):
    """
    Рекомендация следующего действия на основе текущего состояния.
    """
    if not state.get("observations"):
        return "Начните с создания первой локализации наблюдения."
    if not state.get("categories"):
        return "Создайте категории для организации наблюдений."
    if not state.get("photos"):
        return "Загрузите фотографии, чтобы прикрепить к наблюдениям."
    if state.get("search_count", 0) == 0:
        return "Попробуйте поискать наблюдения по ключевым словам."
    return "Продолжайте добавлять новые наблюдения."
